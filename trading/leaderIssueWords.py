# '통합'은 인수합병. 통합검색·통합지수는 그 단어가 아니다.
_TONGHAP_SKIP = ("통합검색", "통합지수")


STOCK_ALIASES = {
    "000660": ("하이닉스", "하닉"),
    "005930": ("삼성전자", "삼전"),
    "180640": ("한진칼",),
    "267850": ("아시아나IDT", "아시아나 IDT"),
    "181710": ("NHN",),
}


def stockNameKeys(name, code=""):
    """제목에 있어야 하는 종목명·별칭. 두 글자 미만은 쓰지 않는다."""
    keys = []
    for raw in (name, *(STOCK_ALIASES.get(str(code) or "", ()))):
        text = str(raw or "").strip()
        if len(text) >= 2 and text not in keys:
            keys.append(text)
    return keys


def _tonghap(low):
    start = 0
    while True:
        found = low.find("통합", start)
        if found < 0:
            return False
        if any(low.startswith(skip, found) for skip in _TONGHAP_SKIP):
            start = found + 2
            continue
        return True


def _hit(title, words):
    low = str(title or "").lower()
    for word in words:
        token = str(word).lower()
        if token == "통합":
            if _tonghap(low):
                return True
            continue
        if token in low:
            return True
    return False


def reasonTag(title):
    """이유 단어의 대표 태그. 없으면 빈 문자열. 우선순위는 표 순서."""
    for canon, words in REASON_MAP:
        if _hit(title, words):
            return canon
    return ""


def themeTag(title, name="", code=""):
    """종목명 헤드라인에서 테마 단어. 이유 표에 없을 때만 급등주가 쓴다.

    종목명·계열 별칭은 테마를 찾기 전에 지운다. 제목 채택 필터는 바꾸지 않는다.
    """
    low = str(title or "").lower()
    if not low:
        return ""
    masks = []
    for raw in list(stockNameKeys(name, code)) + list(THEME_NAME_MASKS):
        text = str(raw or "").strip().lower()
        if len(text) >= 2 and text not in masks:
            masks.append(text)
    for mask in sorted(masks, key=len, reverse=True):
        low = low.replace(mask, " ")
    for key, lab in LEADER_ISSUE_MAP:
        if str(key).lower() in low:
            return lab
    return ""


def leaderIssueTag(title):
    """제목에서 주도주와 같은 첫 단어를 고른다. 없으면 빈 문자열."""
    low = str(title or "").lower()
    if not low:
        return ""
    for key, lab in LEADER_EVENT_MAP:
        if str(key).lower() in low:
            return lab
    for key, lab in LEADER_ISSUE_MAP:
        if str(key).lower() in low:
            return lab
    return ""
