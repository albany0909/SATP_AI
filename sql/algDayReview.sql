-- 알고리즘 당일 거래 복기 (일자·알고리즘별 1건)
-- 원천: 16:05 장마감 복기 (AI_ALG_EVT · AI_STRAT_LIVE_TRADE · AI_ALG_PNL_DAY)
-- REPORT_JSON 에 문제/유지/개선·청산·이벤트 전문 저장

CREATE TABLE IF NOT EXISTS AI_ALG_DAY_REVIEW (
  MODE          VARCHAR(8)    NOT NULL DEFAULT 'paper' COMMENT 'paper|real',
  TRADE_DT      CHAR(8)       NOT NULL COMMENT '거래일 YYYYMMDD',
  ALG_CD        CHAR(5)       NOT NULL COMMENT '알고리즘코드',
  ALG_VER       VARCHAR(16)   NULL COMMENT '알고리즘 버전',
  ALG_NM        VARCHAR(64)   NULL COMMENT '표시명',

  CLOSE_CNT     INT           NOT NULL DEFAULT 0 COMMENT '청산건수',
  WIN_CNT       INT           NOT NULL DEFAULT 0 COMMENT '승',
  LOSS_CNT      INT           NOT NULL DEFAULT 0 COMMENT '패',
  WIN_RATE      DECIMAL(8,2)  NULL COMMENT '승률%',
  DAY_PNL_WON   DECIMAL(18,2) NOT NULL DEFAULT 0 COMMENT '당일실현손익(원)',
  DAY_RET_PCT   DECIMAL(12,6) NULL COMMENT '당일수익률%',
  BUY_CNT       INT           NOT NULL DEFAULT 0 COMMENT '매수이벤트',
  SKIP_CNT      INT           NOT NULL DEFAULT 0 COMMENT '스킵',
  SELL_CNT      INT           NOT NULL DEFAULT 0 COMMENT '매도이벤트',

  REPORT_JSON   MEDIUMTEXT    NOT NULL COMMENT '복기 전문 JSON',
  GENERATED_AT  DATETIME      NULL COMMENT '리포트 생성시각',

  UPDATED_AT    DATETIME      NOT NULL DEFAULT CURRENT_TIMESTAMP
                              ON UPDATE CURRENT_TIMESTAMP,
  CREATED_AT    DATETIME      NOT NULL DEFAULT CURRENT_TIMESTAMP,

  PRIMARY KEY (MODE, TRADE_DT, ALG_CD),
  KEY IDX_AI_ALG_DAY_REV_DT (TRADE_DT),
  KEY IDX_AI_ALG_DAY_REV_ALG (ALG_CD, TRADE_DT)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4
  COMMENT='알고리즘 당일 거래 복기';
