-- 증권사 리포트 요약·가이던스 관리 (네이버 메타·상세 텍스트, PDF 전문 미저장)
CREATE TABLE IF NOT EXISTS AI_RPT_ANAL (
  STK_CD          VARCHAR(20)   NOT NULL COMMENT '종목코드',
  NID             VARCHAR(20)   NOT NULL COMMENT '네이버 리포트 nid',
  STK_NM          VARCHAR(100)  NULL COMMENT '종목명',
  TITLE           VARCHAR(300)  NULL COMMENT '리포트 제목',
  BROKER          VARCHAR(80)   NULL COMMENT '증권사',
  PUB_DT          CHAR(8)       NULL COMMENT '발표일 YYYYMMDD',
  PUB_DT_RAW      VARCHAR(20)   NULL COMMENT '원문 일자표시',
  OPINION         VARCHAR(40)   NULL COMMENT '투자의견',
  TARGET_PRC      BIGINT        NULL COMMENT '목표가(원)',
  TONE_SCORE      INT           NULL COMMENT '제목·요약 톤 점수',
  HAS_GUIDE       CHAR(1)       NOT NULL DEFAULT 'N' COMMENT '가이던스·전망 키워드 Y/N',
  GUIDE_TXT       VARCHAR(800)  NULL COMMENT '가이던스·전망 관련 추출문',
  SUM_TXT         VARCHAR(2000) NULL COMMENT '내용 요약(상세 페이지 텍스트, 일부)',
  DETAIL_URL      VARCHAR(400)  NULL COMMENT '상세 URL',
  PDF_URL         VARCHAR(400)  NULL COMMENT 'PDF URL(링크만)',
  VIEWS           INT           NULL COMMENT '조회수',
  SRC             VARCHAR(20)   NOT NULL DEFAULT 'NAVER' COMMENT '출처',
  PUSHED_YN       CHAR(1)       NOT NULL DEFAULT 'N' COMMENT '텔레그램 푸시 여부',
  PUSHED_AT       DATETIME      NULL COMMENT '푸시 시각',

  CREATED_AT      DATETIME      NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UPDATED_AT      DATETIME      NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,

  PRIMARY KEY (STK_CD, NID),
  KEY IDX_AI_RPT_ANAL_STK_DT (STK_CD, PUB_DT),
  KEY IDX_AI_RPT_ANAL_GUIDE (HAS_GUIDE, PUB_DT),
  KEY IDX_AI_RPT_ANAL_PUSH (PUSHED_YN, CREATED_AT)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4
  COMMENT='증권사 리포트 요약·가이던스 관리';

-- 예상실적/목표가 등 (무료 소스=리포트 파생; FnSpace 유료는 미연동)
CREATE TABLE IF NOT EXISTS AI_CNS_EST (
  STK_CD          VARCHAR(20)   NOT NULL COMMENT '종목코드',
  BASE_DT         CHAR(8)       NOT NULL COMMENT '기준일 YYYYMMDD',
  EST_TP          VARCHAR(20)   NOT NULL COMMENT 'TARGET_PRC/OPINION/SOFT',
  PERIOD_CD       VARCHAR(20)   NOT NULL DEFAULT 'RPT' COMMENT '기간코드 RPT/FY1 등',
  EST_VAL         DECIMAL(20,4) NULL COMMENT '수치(목표가 등)',
  EST_TXT         VARCHAR(200)  NULL COMMENT '의견 문자열 등',
  SRC             VARCHAR(20)   NOT NULL COMMENT 'NAVER_RPT | FNSPACE(미사용)',
  SRC_REF         VARCHAR(40)   NOT NULL DEFAULT '' COMMENT 'nid 등',
  NOTE            VARCHAR(200)  NULL COMMENT '비고',

  CREATED_AT      DATETIME      NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UPDATED_AT      DATETIME      NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,

  PRIMARY KEY (STK_CD, BASE_DT, EST_TP, PERIOD_CD, SRC, SRC_REF),
  KEY IDX_AI_CNS_EST_STK_DT (STK_CD, BASE_DT)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4
  COMMENT='예상·목표가 추정(리포트 파생 등, FnSpace 유료 스킵)';
