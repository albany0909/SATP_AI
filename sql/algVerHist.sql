-- 알고리즘 버전 변경 이력 (스펙 version / 문서 변경 이력과 동기)
CREATE TABLE IF NOT EXISTS AI_ALG_VER_HIST (
  HIST_ID BIGINT NOT NULL AUTO_INCREMENT COMMENT '이력ID',
  ALG_CD CHAR(5) NOT NULL COMMENT '알고리즘코드 MTS01',
  STRAT_ID VARCHAR(40) DEFAULT NULL COMMENT '스펙 stratId',
  ALG_VER INT NOT NULL COMMENT '스펙 version 정수',
  YMD CHAR(10) NOT NULL COMMENT '반영일 YYYY-MM-DD',
  NOTE VARCHAR(500) NOT NULL COMMENT '변경 요약',
  GIT_HASH VARCHAR(16) DEFAULT NULL COMMENT '관련 커밋 짧은해시',
  SRC VARCHAR(16) NOT NULL DEFAULT 'manual' COMMENT 'manual|doc_sync|bump',
  CREATED_AT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UPDATED_AT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (HIST_ID),
  UNIQUE KEY UK_AI_ALG_VER_HIST (ALG_CD, ALG_VER),
  KEY IDX_AI_ALG_VER_HIST_YMD (ALG_CD, YMD)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='알고리즘 버전 변경 이력';
