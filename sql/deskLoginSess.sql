-- 계정 단위 매매 로그인 세션 (중복 로그인 방지)
CREATE TABLE IF NOT EXISTS AI_DESK_LOGIN_SESS (
  LOG_ID       VARCHAR(64)  NOT NULL COMMENT '회원 LOG_ID',
  SESS_TOKEN   VARCHAR(64)  NOT NULL COMMENT '현재 유효 토큰',
  HOST_NM      VARCHAR(128) NULL COMMENT '호스트/PC명',
  LOGIN_AT     DATETIME     NOT NULL COMMENT '로그인 시각',
  HEARTBEAT_AT DATETIME     NOT NULL COMMENT '마지막 생존확인',
  EXPIRES_AT   DATETIME     NOT NULL COMMENT '만료',
  PRIMARY KEY (LOG_ID),
  KEY IX_DESK_SESS_HB (HEARTBEAT_AT)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4
  COMMENT='SATP_AI 계정 단일 로그인 세션';
