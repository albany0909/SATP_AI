-- 계좌 손익 일별 스냅샷
-- 키움 kt00004 당일/당월 손익은 모의에서 0인 경우가 많아,
-- 예탁자산 전일 종가 대비로 당일을 계산하고 월·년은 당일 합으로 관리한다.

CREATE TABLE IF NOT EXISTS AI_ACNT_PNL_DAY (
  MODE          VARCHAR(8)    NOT NULL COMMENT 'paper|real',
  ACNT_NM       VARCHAR(40)   NOT NULL COMMENT '계좌명 (kt00004 acnt_nm)',
  TRADE_DT      CHAR(8)       NOT NULL COMMENT '거래일 YYYYMMDD',

  ASET_EVLT     DECIMAL(18,2) NOT NULL DEFAULT 0 COMMENT '예탁자산평가액 스냅샷',
  OPEN_ASET     DECIMAL(18,2) NULL COMMENT '당일 첫 스냅샷',
  PREV_ASET     DECIMAL(18,2) NULL COMMENT '전 거래일 종가 예탁자산',
  TOT_PUR       DECIMAL(18,2) NULL COMMENT '총매입금액',

  TDY_PNL       DECIMAL(18,2) NOT NULL DEFAULT 0 COMMENT '당일손익(원)',
  TDY_PNL_RT    DECIMAL(12,6) NULL COMMENT '당일손익률%',
  MON_PNL       DECIMAL(18,2) NOT NULL DEFAULT 0 COMMENT '월간손익(원)',
  MON_PNL_RT    DECIMAL(12,6) NULL COMMENT '월간손익률%',
  YEAR_PNL      DECIMAL(18,2) NOT NULL DEFAULT 0 COMMENT '년간손익(원)',
  YEAR_PNL_RT   DECIMAL(12,6) NULL COMMENT '년간손익률%',

  API_TDY_PNL   DECIMAL(18,2) NULL COMMENT 'kt00004 tdy_lspft 원본',
  API_MON_PNL   DECIMAL(18,2) NULL COMMENT 'kt00004 lspft2 당월원본',

  UPDATED_AT    DATETIME      NOT NULL DEFAULT CURRENT_TIMESTAMP
                              ON UPDATE CURRENT_TIMESTAMP,
  CREATED_AT    DATETIME      NOT NULL DEFAULT CURRENT_TIMESTAMP,

  PRIMARY KEY (MODE, ACNT_NM, TRADE_DT),
  KEY IDX_AI_ACNT_PNL_DT (TRADE_DT)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4
  COMMENT='계좌 당일·월간·년간 손익 일별';
