-- 알고리즘별 일별 손익 스냅샷 (웹·매매창 조회용)
-- 원천: AI_STRAT_LIVE_TRADE (EXIT_DT 기준 전량청산 라운드)
-- 당일/월간/누적 승패·손익을 일자 스냅샷에 함께 적재한다.

CREATE TABLE IF NOT EXISTS AI_ALG_PNL_DAY (
  MODE          VARCHAR(8)    NOT NULL COMMENT 'paper|real',
  ALG_CD        CHAR(5)       NOT NULL COMMENT '알고리즘코드 MTS01 등',
  TRADE_DT      CHAR(8)       NOT NULL COMMENT '집계기준일 YYYYMMDD',

  TDY_PNL       DECIMAL(18,2) NOT NULL DEFAULT 0 COMMENT '당일실현손익(원)',
  TDY_PNL_RT    DECIMAL(12,6) NULL COMMENT '당일수익률%(매수금대비)',
  TDY_WIN       INT           NOT NULL DEFAULT 0 COMMENT '당일승',
  TDY_LOSS      INT           NOT NULL DEFAULT 0 COMMENT '당일패',
  TDY_CNT       INT           NOT NULL DEFAULT 0 COMMENT '당일청산건수',
  TDY_BUY_AMT   DECIMAL(18,2) NOT NULL DEFAULT 0 COMMENT '당일매수금액합',

  MON_PNL       DECIMAL(18,2) NOT NULL DEFAULT 0 COMMENT '월간실현손익(원)',
  MON_PNL_RT    DECIMAL(12,6) NULL COMMENT '월간수익률%',
  MON_WIN       INT           NOT NULL DEFAULT 0 COMMENT '월간승',
  MON_LOSS      INT           NOT NULL DEFAULT 0 COMMENT '월간패',
  MON_CNT       INT           NOT NULL DEFAULT 0 COMMENT '월간청산건수',
  MON_BUY_AMT   DECIMAL(18,2) NOT NULL DEFAULT 0 COMMENT '월간매수금액합',

  TOT_PNL       DECIMAL(18,2) NOT NULL DEFAULT 0 COMMENT '누적실현손익(원)',
  TOT_PNL_RT    DECIMAL(12,6) NULL COMMENT '누적수익률%',
  TOT_WIN       INT           NOT NULL DEFAULT 0 COMMENT '누적승',
  TOT_LOSS      INT           NOT NULL DEFAULT 0 COMMENT '누적패',
  TOT_CNT       INT           NOT NULL DEFAULT 0 COMMENT '누적청산건수',
  TOT_BUY_AMT   DECIMAL(18,2) NOT NULL DEFAULT 0 COMMENT '누적매수금액합',

  UPDATED_AT    DATETIME      NOT NULL DEFAULT CURRENT_TIMESTAMP
                              ON UPDATE CURRENT_TIMESTAMP,
  CREATED_AT    DATETIME      NOT NULL DEFAULT CURRENT_TIMESTAMP,

  PRIMARY KEY (MODE, ALG_CD, TRADE_DT),
  KEY IDX_AI_ALG_PNL_DT (TRADE_DT),
  KEY IDX_AI_ALG_PNL_ALG (ALG_CD, TRADE_DT)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4
  COMMENT='알고리즘별 당일·월간·누적 손익 일별';
