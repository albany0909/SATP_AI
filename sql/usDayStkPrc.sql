-- usa06012 미국주식 일봉 적재
-- PK: 종목코드 + 일자

CREATE TABLE IF NOT EXISTS AI_US_DAY_STK_PRC (
  STK_CD          VARCHAR(20)   NOT NULL COMMENT '티커',
  TRADE_DT        CHAR(8)       NOT NULL COMMENT '일자 YYYYMMDD',
  STEX_TP         CHAR(2)       NULL COMMENT '거래소 ND/NY/NA',

  OPEN_PRC        DECIMAL(16,4) NULL COMMENT '시가(USD)',
  HIGH_PRC        DECIMAL(16,4) NULL COMMENT '고가(USD)',
  LOW_PRC         DECIMAL(16,4) NULL COMMENT '저가(USD)',
  CLOSE_PRC       DECIMAL(16,4) NULL COMMENT '종가(USD)',
  PRED_PRE        DECIMAL(16,4) NULL COMMENT '전일대비(USD)',
  FLU_RT          DECIMAL(12,4) NULL COMMENT '등락률(%)',
  TRDE_QTY        BIGINT        NULL COMMENT '누적거래량',
  TRDE_PRICA      DECIMAL(20,4) NULL COMMENT '누적거래대금',
  SRC_TR          VARCHAR(20)   NULL COMMENT '원천 TR (usa06012)',

  CREATED_AT      DATETIME      NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UPDATED_AT      DATETIME      NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,

  PRIMARY KEY (STK_CD, TRADE_DT),
  KEY IDX_AI_US_DAY_STK_PRC_TRADE_DT (TRADE_DT),
  KEY IDX_AI_US_DAY_STK_PRC_STK_DT (STK_CD, TRADE_DT)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4
  COMMENT='usa06012 미국주식 일봉';
