-- 차트 전용 통합(KRX+NXT, SOR) 봉.
-- 조회 종목코드는 명세대로 6자리_AL (ka10081/ka10082/ka10083 stk_cd, SOR:039490_AL).
-- 수정주가 미적용(upd_stkpc_tp=0). SRG01·순위 일봉 AI_DAY_STK_PRC 와 분리한다.
-- 이 파일은 문서다. 이 작업에서 운영 DB 에 실행하지 않는다.

CREATE TABLE AI_CHART_UNIF_PRC (
  STK_CD      VARCHAR(20) NOT NULL COMMENT '6자리 종목코드',
  BAR_TP      CHAR(1)     NOT NULL COMMENT 'D 일봉 W 주봉 M 월봉',
  TRADE_DT    CHAR(8)     NOT NULL COMMENT 'YYYYMMDD',
  OPEN_PRC    BIGINT      NULL,
  HIGH_PRC    BIGINT      NULL,
  LOW_PRC     BIGINT      NULL,
  CLOSE_PRC   BIGINT      NULL,
  TRDE_QTY    BIGINT      NULL,
  CREATED_AT  DATETIME    NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UPDATED_AT  DATETIME    NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (STK_CD, BAR_TP, TRADE_DT),
  KEY IDX_AI_CHART_UNIF_DT (BAR_TP, TRADE_DT)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4
  COMMENT='차트 통합(SOR _AL) 일·주·월봉. 매매 일봉과 분리';
