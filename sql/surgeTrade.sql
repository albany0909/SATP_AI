-- SRG01 급등주매매 로컬 적재용 DDL.
-- 이 파일을 운영 DB 에 실행하지 않는다. 적용은 검토 후 별도 지시.
-- 16:00 미수집 행은 OBSERVED_AT NULL, STATE=NOT_COLLECTED 이다.
-- 그 시각의 순위를 나중에 관측한 값으로 채우지 않는다.

CREATE TABLE IF NOT EXISTS AI_SURGE_RANK_SNAP (
  SNAP_ID        BIGINT       NOT NULL AUTO_INCREMENT,
  TRADE_DT       CHAR(8)      NOT NULL,
  SLOT_CD        VARCHAR(8)   NOT NULL COMMENT '0900..1515, 1518, 1600, ADHOC',
  INTERVAL_MIN   INT          NULL COMMENT '15분 슬롯만 15. 1518/1600/ADHOC 는 NULL',
  QRY_TP         CHAR(1)      NOT NULL COMMENT 'ka00198 4=당일누적',
  EXCHANGE_CD    VARCHAR(8)   NOT NULL DEFAULT 'KRX',
  SRC_TR         VARCHAR(16)  NOT NULL DEFAULT 'ka00198',
  PROVENANCE     VARCHAR(32)  NOT NULL COMMENT 'live|spec_example|synthetic|not_collected',
  OBSERVED_AT    DATETIME     NULL COMMENT '실제 관측 시각. 미수집이면 NULL',
  NOTED_AT       DATETIME     NULL COMMENT '미수집을 기록한 시각',
  STATE_CD       VARCHAR(16)  NOT NULL COMMENT 'COLLECTED|NOT_COLLECTED|ERROR',
  SOURCE_CNT     INT          NOT NULL DEFAULT 0,
  TRUNCATED_YN   CHAR(1)      NULL COMMENT 'Y면 연속조회가 남아 있음. 전수 아님',
  NOTE_TXT       VARCHAR(500) NULL,
  BODY_JSON      JSON         NULL,
  CREATED_AT     DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (SNAP_ID),
  KEY IDX_SURGE_SNAP_DT (TRADE_DT, SLOT_CD)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='SRG01 ka00198 관측 스냅샷';

CREATE TABLE IF NOT EXISTS AI_SURGE_EVENT_AUDIT (
  AUDIT_ID     BIGINT       NOT NULL AUTO_INCREMENT,
  ALG_CD       CHAR(5)      NOT NULL,
  STK_CD       VARCHAR(12)  NOT NULL,
  EVENT_ID     VARCHAR(40)  NOT NULL,
  EVENT_DT     CHAR(8)      NOT NULL COMMENT '같은 이벤트의 최초 급등일',
  TAG_TXT      VARCHAR(12)  NOT NULL,
  SOURCE_URL   VARCHAR(300) NOT NULL,
  PUBLISHED_AT VARCHAR(32)  NOT NULL,
  NOTE_TXT     VARCHAR(200) NULL,
  PROVENANCE   VARCHAR(32)  NOT NULL DEFAULT 'explicit_audit',
  CREATED_AT   DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (AUDIT_ID),
  UNIQUE KEY UK_SURGE_EVENT (ALG_CD, STK_CD, EVENT_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='SRG01 사람이 확인한 이슈. 자동 매수 스위치가 아님';
