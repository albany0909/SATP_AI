-- ka10099 종목정보 리스트 캐시 (종목명↔코드 해석용)

CREATE TABLE AI_STK_INFO (
  STK_CD          VARCHAR(20)   NOT NULL COMMENT '종목코드(단축, 정규화)',
  STK_NM          VARCHAR(80)   NOT NULL COMMENT '종목명',
  MRKT_TP         VARCHAR(4)    NULL COMMENT '조회 시장구분(요청값 0/10/...)',
  MARKET_CODE     VARCHAR(20)   NULL COMMENT '시장구분코드(응답)',
  MARKET_NAME     VARCHAR(40)   NULL COMMENT '시장명',
  LIST_CNT        BIGINT        NULL COMMENT '상장주식수',
  REG_DAY         CHAR(8)       NULL COMMENT '상장일 YYYYMMDD',
  LAST_PRICE      BIGINT        NULL COMMENT '전일종가',
  STATE           VARCHAR(40)   NULL COMMENT '종목상태',
  UP_NAME         VARCHAR(40)   NULL COMMENT '업종명',
  NXT_ENABLE      CHAR(1)       NULL COMMENT 'NXT가능 Y/N',
  SRC_TR          VARCHAR(20)   NULL COMMENT '원천 TR (ka10099)',
  CREATED_AT      DATETIME      NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UPDATED_AT      DATETIME      NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,

  PRIMARY KEY (STK_CD),
  KEY IDX_AI_STK_INFO_NM (STK_NM),
  KEY IDX_AI_STK_INFO_MRKT (MRKT_TP)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4
  COMMENT='ka10099 종목정보 리스트 캐시';
