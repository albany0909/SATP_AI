-- 주식 주봉(ka10082)·월봉(ka10083) 차트 적재.
-- 일봉은 기존 AI_DAY_STK_PRC 를 그대로 쓴다.
-- 이 파일은 문서다. 이 작업에서 운영 DB 에 실행하지 않는다.

CREATE TABLE AI_WK_STK_PRC (
  STK_CD      VARCHAR(20) NOT NULL COMMENT '종목코드',
  TRADE_DT    CHAR(8)     NOT NULL COMMENT '주봉 일자 YYYYMMDD',
  OPEN_PRC    BIGINT      NULL COMMENT '시가',
  HIGH_PRC    BIGINT      NULL COMMENT '고가',
  LOW_PRC     BIGINT      NULL COMMENT '저가',
  CLOSE_PRC   BIGINT      NULL COMMENT '종가',
  TRDE_QTY    BIGINT      NULL COMMENT '거래량',
  CREATED_AT  DATETIME    NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UPDATED_AT  DATETIME    NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (STK_CD, TRADE_DT)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4
  COMMENT='ka10082 주식주봉';

CREATE TABLE AI_MON_STK_PRC (
  STK_CD      VARCHAR(20) NOT NULL COMMENT '종목코드',
  TRADE_DT    CHAR(8)     NOT NULL COMMENT '월봉 일자 YYYYMMDD',
  OPEN_PRC    BIGINT      NULL COMMENT '시가',
  HIGH_PRC    BIGINT      NULL COMMENT '고가',
  LOW_PRC     BIGINT      NULL COMMENT '저가',
  CLOSE_PRC   BIGINT      NULL COMMENT '종가',
  TRDE_QTY    BIGINT      NULL COMMENT '거래량',
  CREATED_AT  DATETIME    NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UPDATED_AT  DATETIME    NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (STK_CD, TRADE_DT)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4
  COMMENT='ka10083 주식월봉';
