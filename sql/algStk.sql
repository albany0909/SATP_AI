-- 알고리즘별 관리종목 (차트·실매매 유니버스)
-- 키: ALG_CD(5) + STK_CD(6). 관심종목(AI_WATCH_STK)과 분리한다.

CREATE TABLE IF NOT EXISTS AI_ALG_STK (
  ALG_CD      CHAR(5)       NOT NULL COMMENT '알고리즘코드 (MTS01)',
  STK_CD      CHAR(6)       NOT NULL COMMENT '종목코드 6자리',
  STK_NM      VARCHAR(80)   NULL COMMENT '종목명',
  STATUS      CHAR(1)       NOT NULL DEFAULT 'Y' COMMENT 'Y활성 N비활성',
  SRC         VARCHAR(40)   NULL COMMENT '출처 web/rank16h/watch',
  NOTE        VARCHAR(200)  NULL COMMENT '메모',
  CREATED_AT  DATETIME      NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UPDATED_AT  DATETIME      NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,

  PRIMARY KEY (ALG_CD, STK_CD),
  KEY IDX_AI_ALG_STK_STS (ALG_CD, STATUS),
  KEY IDX_AI_ALG_STK_STK (STK_CD, STATUS)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4
  COMMENT='알고리즘별 관리종목';
