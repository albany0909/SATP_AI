-- 매매창 공유 설정 (톰캣 조회용). main 이 patchSettings 시 UPSERT.
CREATE TABLE IF NOT EXISTS AI_DESK_CFG (
  CFG_KEY     VARCHAR(64)  NOT NULL COMMENT 'settings 등',
  CFG_JSON    LONGTEXT     NOT NULL COMMENT 'JSON 본문',
  UPDATED_AT  DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (CFG_KEY)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4
  COMMENT='SATP_AI 매매창 공유 설정';
