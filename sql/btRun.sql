-- 전략 백테스트(시뮬레이션) 실행 이력
-- AI_BT_RUN: 실행 헤더 / AI_BT_TRADE: 체결 상세

CREATE TABLE AI_BT_RUN (
  BT_RUN_ID       BIGINT        NOT NULL AUTO_INCREMENT COMMENT '실행ID',

  STRAT_ID        VARCHAR(64)   NOT NULL COMMENT '스펙 파일명(내부 로드용)',
  ALG_CD          CHAR(5)       NOT NULL DEFAULT '' COMMENT '알고리즘코드 (MTS01)',
  STRAT_NAME      VARCHAR(128)  NULL COMMENT '전략명',
  STK_CD          VARCHAR(20)   NOT NULL COMMENT '종목코드',

  START_DT        CHAR(8)       NOT NULL COMMENT '시뮬 시작일 YYYYMMDD',
  END_DT          CHAR(8)       NOT NULL COMMENT '시뮬 종료일 YYYYMMDD',
  WARMUP_DT       CHAR(8)       NULL COMMENT '워밍업 시작일 YYYYMMDD',

  INIT_CASH       DECIMAL(18,2) NOT NULL COMMENT '초기투자금',
  TIC_SCOPE       VARCHAR(2)    NOT NULL DEFAULT '1' COMMENT '분봉 틱범위',
  BAR_SOURCE      VARCHAR(8)    NOT NULL DEFAULT 'min' COMMENT 'min|tic',

  STATUS          VARCHAR(8)    NOT NULL COMMENT 'OK|FAIL',
  ERR_MSG         VARCHAR(1000) NULL COMMENT '실패 원인',

  BAR_CNT         INT           NULL COMMENT '사용 봉/틱 수',
  TRADE_CNT       INT           NULL COMMENT '라운드트립 거래 수',
  WIN_CNT         INT           NULL COMMENT '승',
  LOSS_CNT        INT           NULL COMMENT '패',
  WIN_RATE        DECIMAL(10,4) NULL COMMENT '승률%',
  AVG_RET_PCT     DECIMAL(12,6) NULL COMMENT '평균수익률%',
  FINAL_RET_PCT   DECIMAL(12,6) NULL COMMENT '복리수익률%',
  MAX_DD_PCT      DECIMAL(12,6) NULL COMMENT 'MDD%',
  EQUITY_END      DECIMAL(18,2) NULL COMMENT '종료 자산',

  PARAMS_JSON     TEXT          NULL COMMENT '전략 파라미터 JSON',
  RESULT_MSG      TEXT          NULL COMMENT '텔레그램 리포트 원문',

  CREATED_AT      DATETIME      NOT NULL DEFAULT CURRENT_TIMESTAMP,

  PRIMARY KEY (BT_RUN_ID),
  KEY IDX_AI_BT_RUN_ALG_DT (ALG_CD, START_DT, END_DT),
  KEY IDX_AI_BT_RUN_STRAT_DT (STRAT_ID, START_DT, END_DT),
  KEY IDX_AI_BT_RUN_STK_DT (STK_CD, START_DT),
  KEY IDX_AI_BT_RUN_CREATED (CREATED_AT)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4
  COMMENT='전략 백테스트 실행 이력';

CREATE TABLE AI_BT_TRADE (
  BT_RUN_ID       BIGINT        NOT NULL COMMENT '실행ID',
  SEQ             INT           NOT NULL COMMENT '체결 순번(1..)',

  SIDE            VARCHAR(8)    NOT NULL COMMENT 'BUY|SELL',
  CNTR_TM         VARCHAR(32)   NULL COMMENT '체결시각',
  TRADE_DT        CHAR(8)       NULL COMMENT '일자 YYYYMMDD',
  PRICE           DECIMAL(18,4) NULL COMMENT '체결가',
  REASON          VARCHAR(64)   NULL COMMENT '사유',

  PRIMARY KEY (BT_RUN_ID, SEQ),
  KEY IDX_AI_BT_TRADE_DT (TRADE_DT),
  CONSTRAINT FK_AI_BT_TRADE_RUN
    FOREIGN KEY (BT_RUN_ID) REFERENCES AI_BT_RUN (BT_RUN_ID)
    ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4
  COMMENT='전략 백테스트 체결 상세';
