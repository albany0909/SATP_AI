-- 관심종목 공시(DART) — 전문 본문 미저장, 메타·링크만
CREATE TABLE IF NOT EXISTS AI_STK_DISC (
  STK_CD          VARCHAR(20)   NOT NULL COMMENT '종목코드',
  RCEPT_NO        VARCHAR(20)   NOT NULL COMMENT '접수번호(공시 키)',
  STK_NM          VARCHAR(100)  NULL COMMENT '종목명',
  CORP_CODE       VARCHAR(20)   NULL COMMENT 'DART 법인코드',
  CORP_NAME       VARCHAR(200)  NULL COMMENT '공시 법인명',
  REPORT_NM       VARCHAR(300)  NULL COMMENT '공시 제목',
  RCEPT_DT        CHAR(8)       NULL COMMENT '접수일 YYYYMMDD',
  FLR_NM          VARCHAR(100)  NULL COMMENT '제출인',
  RM              VARCHAR(40)   NULL COMMENT '비고(유상 등)',
  VIEW_URL        VARCHAR(400)  NULL COMMENT '공시 뷰어 URL',
  SRC             VARCHAR(20)   NOT NULL DEFAULT 'DART' COMMENT '출처',
  PUSHED_YN       CHAR(1)       NOT NULL DEFAULT 'N' COMMENT '텔레그램 신규 푸시',
  PUSHED_AT       DATETIME      NULL,
  CREATED_AT      DATETIME      NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UPDATED_AT      DATETIME      NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,

  PRIMARY KEY (RCEPT_NO),
  KEY IDX_AI_STK_DISC_STK_DT (STK_CD, RCEPT_DT),
  KEY IDX_AI_STK_DISC_PUSH (PUSHED_YN, CREATED_AT)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4
  COMMENT='관심종목 DART 공시 메타';

-- 관심종목 뉴스·이슈 메타 (네이버 페이 증권 등, 본문 미저장)
CREATE TABLE IF NOT EXISTS AI_STK_NEWS (
  STK_CD          VARCHAR(20)   NOT NULL COMMENT '종목코드',
  NEWS_ID         VARCHAR(80)   NOT NULL COMMENT '기사 고유키 office_article',
  STK_NM          VARCHAR(100)  NULL COMMENT '종목명',
  TITLE           VARCHAR(400)  NULL COMMENT '제목',
  OFFICE_NM       VARCHAR(80)   NULL COMMENT '언론사',
  PUB_DT          CHAR(8)       NULL COMMENT '일자 YYYYMMDD',
  PUB_TM          VARCHAR(20)   NULL COMMENT '시각/표시',
  NEWS_URL        VARCHAR(500)  NULL COMMENT '기사 URL',
  SRC             VARCHAR(20)   NOT NULL DEFAULT 'NAVER' COMMENT '출처',
  ISSUE_YN        CHAR(1)       NOT NULL DEFAULT 'N' COMMENT '이슈 키워드 포함',
  PUSHED_YN       CHAR(1)       NOT NULL DEFAULT 'N',
  PUSHED_AT       DATETIME      NULL,
  CREATED_AT      DATETIME      NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UPDATED_AT      DATETIME      NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,

  PRIMARY KEY (STK_CD, NEWS_ID),
  KEY IDX_AI_STK_NEWS_DT (PUB_DT, STK_CD),
  KEY IDX_AI_STK_NEWS_PUSH (PUSHED_YN, CREATED_AT),
  KEY IDX_AI_STK_NEWS_ISSUE (ISSUE_YN, PUB_DT)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4
  COMMENT='관심종목 뉴스·이슈 메타';
