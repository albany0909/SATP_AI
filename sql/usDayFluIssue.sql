-- usa20930 미국주식 가격급등락 일별 스냅샷 (+ 테마)
-- PK: 일자 + 급등락구분 + 순위

CREATE TABLE IF NOT EXISTS AI_US_DAY_FLU_ISSUE (
  TRADE_DT          CHAR(8)       NOT NULL COMMENT '미장세션일자 YYYYMMDD',
  FLU_TP            CHAR(1)       NOT NULL COMMENT '1:급등 2:급락',
  RANK_NO           INT           NOT NULL COMMENT '등락률 순위(1=최상위)',

  STK_CD            VARCHAR(20)   NOT NULL COMMENT '티커',
  STK_NM            VARCHAR(80)   NULL COMMENT '종목명한글',
  STK_ENM           VARCHAR(120)  NULL COMMENT '영문종목명',
  STEX_TP           CHAR(2)       NULL COMMENT '거래소 ND/NY/NA',
  IND_GRP           VARCHAR(40)   NULL COMMENT '테마/업종그룹',

  FLU_RT            DECIMAL(12,4) NULL COMMENT '등락률(%)',
  CUR_PRC           DECIMAL(16,4) NULL COMMENT '현재가(USD)',
  PRED_PRE          DECIMAL(16,4) NULL COMMENT '전일대비(USD)',
  BASE_PRIC         DECIMAL(16,4) NULL COMMENT '기준가(USD)',
  ACC_TRDE_QTY      DECIMAL(20,0) NULL COMMENT '거래량',
  SDNIN_RT          DECIMAL(12,4) NULL COMMENT '급증률',
  PRED_PRE_SIG      CHAR(1)       NULL COMMENT '전일대비기호',
  SRC_TR            VARCHAR(20)   NULL COMMENT '원천 TR (usa20930)',

  CREATED_AT        DATETIME      NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UPDATED_AT        DATETIME      NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,

  PRIMARY KEY (TRADE_DT, FLU_TP, RANK_NO),
  KEY IDX_AI_US_DAY_FLU_STK (STK_CD, TRADE_DT),
  KEY IDX_AI_US_DAY_FLU_DT_TP (TRADE_DT, FLU_TP),
  KEY IDX_AI_US_DAY_FLU_IND (TRADE_DT, FLU_TP, IND_GRP)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4
  COMMENT='usa20930 미국주식 가격급등락 이슈';
